import type { Ingredient, Recipe } from './types';

export const SEED_ID_PREFIX = 'seed-';

const SEED_CREATED_AT = '2026-11-01T00:00:00.000Z';

type SeedIngredient = [name: string, amount: number | null, unit: string];

export function isSeedRecipe(recipe: Recipe): boolean {
  return recipe.id.startsWith(SEED_ID_PREFIX);
}

function makeIngredient(recipeId: string, index: number, [name, amount, unit]: SeedIngredient): Ingredient {
  return {
    id: `${recipeId}-ing-${index + 1}`,
    name,
    amount,
    unit,
  };
}

function makeRecipe(
  ownerId: string,
  slug: string,
  title: string,
  baseServings: number,
  ingredients: SeedIngredient[],
  steps: string[],
): Recipe {
  const id = `${SEED_ID_PREFIX}${slug}`;
  return {
    id,
    title,
    baseServings,
    ingredients: ingredients.map((ingredient, index) => makeIngredient(id, index, ingredient)),
    steps,
    ownerId,
    createdAt: SEED_CREATED_AT,
  };
}

